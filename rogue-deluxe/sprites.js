function shade(hex, f) {   // f < 1 darker, f > 1 toward white
  const n = parseInt(hex.slice(1), 16);
  let r = n >> 16, g = (n >> 8) & 255, b = n & 255;
  if (f < 1) { r *= f; g *= f; b *= f; } else { const t = f - 1; r += (255 - r) * t; g += (255 - g) * t; b += (255 - b) * t; }
  return '#' + [r, g, b].map(v => Math.round(v).toString(16).padStart(2, '0')).join('');
}

const spriteCache = new Map();
// a 16×16 canvas for a sprite; tint colours x/X/z; mode 'flash' paints it all white
function sprite(name, tint, mode) {
  const key = name + '|' + (tint || '') + '|' + (mode || '');
  let c = spriteCache.get(key);
  if (c) return c;
  c = document.createElement('canvas'); c.width = c.height = 16;
  const g = c.getContext('2d'), rows = SPR[name];
  const pal = Object.assign({}, PAL);
  if (tint) { pal.x = tint; pal.X = shade(tint, .62); pal.z = shade(tint, 1.55); }
  for (let y = 0; y < 16; y++) for (let x = 0; x < 16; x++) {
    const ch = rows[y][x];
    if (!ch || ch === '.') continue;
    g.fillStyle = mode === 'flash' ? (ch === 'k' ? '#ffffff' : '#ffffff') : (pal[ch] || '#f0f');
    g.fillRect(x, y, 1, 1);
  }
  spriteCache.set(key, c);
  return c;
}

// ── map tiles, painted with a little seeded noise so the floor doesn't look tiled ──
function rng(seed) { return () => { seed = (seed * 1103515245 + 12345) & 0x7fffffff; return seed / 0x7fffffff; }; }
function tile(name, variant = 0) {
  const key = 'tile|' + name + '|' + variant;
  let c = spriteCache.get(key);
  if (c) return c;
  c = document.createElement('canvas'); c.width = c.height = 16;
  const g = c.getContext('2d'), R = rng(variant * 7919 + name.length * 31 + 1);
  const px = (x, y, col) => { g.fillStyle = col; g.fillRect(x, y, 1, 1); };
  const rect = (x, y, w, h, col) => { g.fillStyle = col; g.fillRect(x, y, w, h); };
  if (name === 'floor' || name === 'trap') {
    rect(0, 0, 16, 16, '#2b2733');
    // four slabs, each a slightly different stone
    for (const [sx, sy] of [[0, 0], [8, 0], [0, 8], [8, 8]]) {
      const base = ['#4a4556', '#46414f', '#4d4859', '#433e4c'][Math.floor(R() * 4)];
      rect(sx, sy, 7, 7, base);
      rect(sx, sy, 7, 1, shade(base, 1.12)); rect(sx, sy, 1, 7, shade(base, 1.08));
      for (let i = 0; i < 3; i++) px(sx + 1 + Math.floor(R() * 5), sy + 1 + Math.floor(R() * 5), shade(base, .85));
    }
    if (name === 'trap') {
      // a glowing rune plate
      rect(3, 3, 10, 10, '#2a1830'); rect(4, 4, 8, 8, '#4a2050');
      for (const [x, y] of [[7, 4], [8, 4], [4, 7], [4, 8], [11, 7], [11, 8], [7, 11], [8, 11], [6, 6], [9, 6], [6, 9], [9, 9], [7, 7], [8, 8], [7, 8], [8, 7]])
        px(x, y, '#ff5ad8');
      rect(3, 3, 10, 1, '#1b1424'); rect(3, 12, 10, 1, '#1b1424'); rect(3, 3, 1, 10, '#1b1424'); rect(12, 3, 1, 10, '#1b1424');
    }
  } else if (name === 'wall') {
    rect(0, 0, 16, 16, '#3f3730');
    for (let row = 0; row < 4; row++) {
      const off = row % 2 ? 4 : 0;
      for (let bx = -8; bx < 16; bx += 8) {
        const x0 = bx + off, y0 = row * 4;
        const base = ['#7a6b5c', '#73655a', '#806f5e', '#6e6155'][Math.floor(R() * 4)];
        const x1 = Math.max(0, x0), x2 = Math.min(16, x0 + 7);
        if (x2 <= x1) continue;
        rect(x1, y0, x2 - x1, 3, base);
        rect(x1, y0, x2 - x1, 1, shade(base, 1.15));
        if (R() < .5) px(x1 + Math.floor(R() * (x2 - x1)), y0 + 1 + Math.floor(R() * 2), shade(base, .82));
      }
    }
  } else if (name === 'passage') {
    rect(0, 0, 16, 16, '#3a3129');
    for (let i = 0; i < 70; i++) px(Math.floor(R() * 16), Math.floor(R() * 16), ['#4a3f33', '#5a4c3c', '#30281f', '#463a2e'][Math.floor(R() * 4)]);
    for (let i = 0; i < 4; i++) { const x = Math.floor(R() * 13), y = Math.floor(R() * 13); rect(x, y, 3, 2, '#5e5244'); rect(x, y, 3, 1, '#6e6050'); }
  } else if (name === 'door') {
    rect(0, 0, 16, 16, '#3f3730');
    rect(2, 1, 12, 15, '#1b1424');
    rect(3, 2, 10, 14, '#8a5a30');
    for (const x of [5, 8, 11]) rect(x, 2, 1, 14, '#5e3a22');
    rect(3, 2, 10, 1, '#a87240');
    rect(3, 5, 10, 1, '#4a2e1a'); rect(3, 12, 10, 1, '#4a2e1a');
    rect(10, 8, 2, 2, '#f6d24a');
  } else if (name === 'stairs') {
    rect(0, 0, 16, 16, '#2b2733');
    rect(1, 1, 14, 14, '#1b1424');
    const steps = ['#8a8494', '#6e6878', '#555060', '#3e3a48', '#2a2732'];
    steps.forEach((col, i) => { rect(2 + i, 2 + i * 2, 12 - i * 2, 2, col); rect(2 + i, 2 + i * 2, 12 - i * 2, 1, shade(col, 1.2)); });
    rect(7, 12, 2, 2, '#0e0b12');
  }
  spriteCache.set(key, c);
  return c;
}
